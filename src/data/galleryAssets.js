/**
 * Filter gallery assets by category, query, and type
 */
export function filterGalleryAssets({ category = 'all', query = '', type = 'all' } = {}) {
  let list = GALLERY_ASSETS;

  if (category && category !== 'all' && category !== 'custom') {
    list = list.filter((item) => item.category === category);
  }

  if (type && type !== 'all') {
    list = list.filter((item) => item.type === type);
  }

  if (query && query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter(
      (item) =>
        item.title.toLowerCase().includes(q) ||
        item.path.toLowerCase().includes(q) ||
        item.filename.toLowerCase().includes(q) ||
        item.category.toLowerCase().includes(q) ||
        item.tags.some((t) => t.toLowerCase().includes(q))
    );
  }

  return list;
}

/**
 * Quick presets helper for a given robot slug
 */
export function getPresetsForRobot(slug = 'aurra') {
  const normSlug = String(slug || '').toLowerCase().trim();
  const matched = GALLERY_ASSETS.filter((item) => item.category === normSlug && item.isPreset);
  if (matched.length > 0) return matched;

  // Fallback to hero + first 4 steps of category
  const allInCat = GALLERY_ASSETS.filter((item) => item.category === normSlug);
  if (allInCat.length > 0) return allInCat.slice(0, 6);

  // General fallback
  return GALLERY_ASSETS.filter((item) => item.isPreset).slice(0, 6);
}

/**
 * Find image asset by path
 */
export function findAssetByPath(path) {
  if (!path) return null;
  const clean = String(path).trim().toLowerCase();
  return GALLERY_ASSETS.find((a) => a.path.toLowerCase() === clean) || null;
}
